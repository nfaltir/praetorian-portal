/*
  Regenerates src/db/auth-schema.ts from the Better Auth config, then makes
  every timestamp column timezone-aware (timestamptz).
  Run: npm run auth:schema
*/
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const out = "src/db/auth-schema.ts";
execSync(`npx auth generate --config src/lib/auth.ts --output ${out} --yes`, { stdio: "inherit" });

let src = readFileSync(out, "utf8");
src = src.replace(/timestamp\("([a-z_]+)"\)/g, 'timestamp("$1", { withTimezone: true })');
src = "/* GENERATED by npm run auth:schema. Do not edit by hand. */\n" + src;
writeFileSync(out, src);
console.log("auth-schema.ts: timestamps set to timestamptz");
